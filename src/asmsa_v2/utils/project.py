"""Project configuration shared across the notebook pipeline.

v1 passed state between its six notebooks by writing a Python file and
``exec``-ing it:

    with open('inputs.py','w') as i: i.write(f"base = '{base}' ...")
    # ...and in every later notebook:
    exec(open('inputs.py').read())

That has no validation (a typo surfaces as a ``NameError`` five notebooks
later), no record of which stages have run, no defence against the notebooks
disagreeing about where files live, and it injects arbitrary names into the
global namespace.

:class:`Project` replaces it with a validated, YAML-backed object that also
owns the directory layout and can report which pipeline stages are complete.
"""
from __future__ import annotations

import json
import shutil
import sys
from dataclasses import dataclass, field, asdict, fields
from pathlib import Path
from typing import Any

CONFIG_NAME = "asmsa.yaml"

# Fixed, numbered directory layout, mirroring v1's convention so the
# artifacts of each stage are obvious from the filesystem alone.
LAYOUT = {
    "datasets": "01-datasets",
    "tuning": "02-tuning",
    "models": "03-models",
    "md": "04-md",
    "analysis": "05-analysis",
    "logs": "logs",
}


@dataclass
class Project:
    """Everything the pipeline needs to know about one system.

    Parameters
    ----------
    name : str
        Short identifier used as a file stem, e.g. ``"trpcage"``.
    root : path
        Working directory; all stage directories live inside it.
    conf : str
        Input conformation (PDB). By ASMSA convention it contains **no
        hydrogens** — ``pdb2gmx`` adds them.
    traj : str
        Input trajectory (XTC/DCD/...), with atom numbering matching ``conf``.
    components : mapping, optional
        mdtraj selection strings naming the parts of a complex, e.g.
        ``{"protein": "protein", "ligand": "resname LIG"}``. Leave empty for a
        single-molecule system; the pipeline then uses whole-molecule features
        only, reproducing v1's behaviour.
    model_name : str
        Names the trained model and its exported artifacts. Set it to the
        prior you are using (``"norm"``, ``"unif"``, ``"mix"``) to keep
        several models side by side, as v1 did.
    prior : str
        ``"normal"``, ``"uniform"``, ``"mix"`` (Gaussians on a circle), or a
        path to a grayscale image for an image prior.
    latent_dim : int
        Number of collective variables. 2 is the usual choice: it is what
        metadynamics can still grid cheaply, and what a plot can show.
    """

    name: str
    root: Path = Path(".")
    conf: str = ""
    traj: str = ""
    components: dict[str, str] = field(default_factory=dict)

    # generated by pdb2gmx
    topol: str = ""
    index: str = ""
    gro: str = ""

    # featurization
    nb_density: int = 2
    inter_strategy: str = "ca_heavy"
    use_dihedrals: bool = True
    scaler_method: str = "standard"

    # splitting
    split_strategy: str = "chronological"
    split_fractions: tuple[float, float, float] = (0.7, 0.15, 0.15)
    rmsd_decorrelate_nm: float | None = None

    # model
    model_name: str = "norm"
    prior: str = "normal"
    latent_dim: int = 2
    time_lag: int = 0            # 0 = instantaneous; >0 = time-lagged target

    # md
    temperature: float = 300.0
    pressure: float = 1.0
    dt: float = 0.002
    box_nm: float = 1.2
    production_ns: float = 100.0

    # bookkeeping
    created: str = ""
    asmsa_version: str = ""

    def __post_init__(self):
        self.root = Path(self.root).expanduser().resolve()
        if not self.topol:
            self.topol = f"{self.name}.top"
        if not self.index:
            self.index = f"{self.name}.ndx"
        if not self.gro:
            self.gro = f"{self.name}.gro"
        self.split_fractions = tuple(float(x) for x in self.split_fractions)
        if not self.asmsa_version:
            from .. import __version__
            self.asmsa_version = __version__
        if not self.created:
            from datetime import datetime
            self.created = datetime.now().isoformat(timespec="seconds")

    # ------------------------------------------------------------------ paths
    def dir(self, which: str) -> Path:
        """Path to a stage directory, created on demand."""
        if which not in LAYOUT:
            raise KeyError(f"unknown stage {which!r}; known: {sorted(LAYOUT)}")
        p = self.root / LAYOUT[which]
        p.mkdir(parents=True, exist_ok=True)
        return p

    def path(self, *parts: str) -> Path:
        """Path relative to the project root."""
        return self.root.joinpath(*parts)

    def ensure_dirs(self) -> None:
        for which in LAYOUT:
            self.dir(which)

    @property
    def conf_path(self) -> Path:
        return self._resolve(self.conf)

    @property
    def traj_path(self) -> Path:
        return self._resolve(self.traj)

    def _resolve(self, name: str) -> Path:
        if not name:
            return self.root / "<unset>"
        p = Path(name).expanduser()
        return p if p.is_absolute() else self.root / p

    # Canonical artifact names, so no two notebooks can disagree about them.
    @property
    def features_file(self) -> Path:   return self.dir("datasets") / "features.pt"
    @property
    def scaler_file(self) -> Path:     return self.dir("datasets") / "scaler.npz"
    @property
    def split_file(self) -> Path:      return self.dir("datasets") / "split.npz"
    @property
    def molecule_file(self) -> Path:   return self.dir("datasets") / "molecule.json"
    @property
    def tuning_file(self) -> Path:     return self.dir("tuning") / "tuning.json"
    @property
    def checkpoint_file(self) -> Path:
        return self.dir("models") / f"{self.model_name}.pt"
    @property
    def cv_stem(self) -> str:          return f"cv-{self.model_name}"
    @property
    def plumed_model_file(self) -> Path:
        return self.dir("models") / f"{self.cv_stem}-plumed.pt"
    @property
    def batch_model_file(self) -> Path:
        return self.dir("models") / f"{self.cv_stem}-batch.pt"
    @property
    def plumed_dat(self) -> Path:      return self.dir("md") / "plumed.dat"

    # -------------------------------------------------------------------- i/o
    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["root"] = str(self.root)
        d["split_fractions"] = list(self.split_fractions)
        return d

    def save(self, path: str | Path | None = None) -> Path:
        """Write ``asmsa.yaml`` (falls back to JSON if PyYAML is absent)."""
        self.root.mkdir(parents=True, exist_ok=True)
        path = Path(path) if path else self.root / CONFIG_NAME
        data = self.to_dict()
        try:
            import yaml
            text = yaml.safe_dump(data, sort_keys=False, default_flow_style=False)
        except ImportError:
            path = path.with_suffix(".json")
            text = json.dumps(data, indent=2)
        path.write_text(text)
        return path

    @classmethod
    def load(cls, path: str | Path = ".") -> "Project":
        """Load a project from a directory or an explicit config file."""
        p = Path(path).expanduser()
        if p.is_dir():
            for cand in (p / CONFIG_NAME, p / "asmsa.json"):
                if cand.exists():
                    p = cand
                    break
            else:
                raise FileNotFoundError(
                    f"no {CONFIG_NAME} in {p}. Create one in the setup notebook:\n"
                    f"    Project(name='mysystem', root='{p}', "
                    f"conf='conf.pdb', traj='traj.xtc').save()"
                )
        text = p.read_text()
        if p.suffix in (".yaml", ".yml"):
            import yaml
            data = yaml.safe_load(text)
        else:
            data = json.loads(text)
        known = {f.name for f in fields(cls)}
        unknown = set(data) - known
        if unknown:
            raise ValueError(
                f"{p} contains unknown keys {sorted(unknown)}; it may have been "
                f"written by a different asmsa_v2 version"
            )
        data.setdefault("root", str(p.parent))
        return cls(**data)

    # ------------------------------------------------------------ diagnostics
    def stage_status(self) -> dict[str, bool]:
        """Which pipeline stages have produced their artifacts."""
        return {
            "01 prepare (features)": self.features_file.exists(),
            "01 prepare (scaler)": self.scaler_file.exists(),
            "01 prepare (split)": self.split_file.exists(),
            "02 tune": self.tuning_file.exists(),
            "03 train (checkpoint)": self.checkpoint_file.exists(),
            "04 export (plumed model)": self.plumed_model_file.exists(),
            "04 export (plumed.dat)": self.plumed_dat.exists(),
            "05 md (HILLS)": (self.dir("md") / "HILLS").exists(),
            "05 md (trajectory)": (self.dir("md") / "md.xtc").exists(),
        }

    def check(self, require_gromacs: bool = False) -> "PreflightReport":
        """Validate inputs and report the environment.

        Run this as the first cell of every notebook: it turns problems that
        would otherwise appear as a confusing traceback twenty cells later
        into one readable table.
        """
        rows: list[tuple[str, str, str]] = []

        def add(label, ok, detail):
            rows.append((label, "ok" if ok else ("warn" if ok is None else "fail"),
                         detail))

        add("project root", self.root.is_dir(), str(self.root))

        for label, p in (("input conformation", self.conf_path),
                         ("input trajectory", self.traj_path)):
            add(label, p.exists(), f"{p}" + ("" if p.exists() else "  MISSING"))

        n_atoms_conf = n_frames = None
        if self.conf_path.exists() and self.traj_path.exists():
            try:
                import mdtraj as md
                top = md.load(str(self.conf_path))
                n_atoms_conf = top.n_atoms
                tr = md.load(str(self.traj_path), top=str(self.conf_path))
                n_frames = tr.n_frames
                add("trajectory loads", True,
                    f"{n_frames} frames x {tr.n_atoms} atoms")
                add("atom counts match", tr.n_atoms == n_atoms_conf,
                    f"conf {n_atoms_conf} vs traj {tr.n_atoms}"
                    + ("" if tr.n_atoms == n_atoms_conf else
                       "  -- the PDB and trajectory describe different systems"))
                n_h = len(top.top.select("element H"))
                add("conformation has no hydrogens", n_h == 0 or None,
                    "no hydrogens" if n_h == 0 else
                    f"{n_h} hydrogens present; ASMSA's protocol expects a "
                    f"hydrogen-free PDB so pdb2gmx can add them consistently")
                if self.components:
                    for cname, sel in self.components.items():
                        try:
                            idx = top.top.select(sel)
                            add(f"component {cname!r}", len(idx) > 0,
                                f"{len(idx)} atoms  (selection: {sel!r})")
                        except Exception as exc:
                            add(f"component {cname!r}", False,
                                f"invalid selection {sel!r}: {exc}")
            except Exception as exc:
                add("trajectory loads", False, f"{type(exc).__name__}: {exc}")

        # environment
        try:
            import torch
            from .config import resolve_device
            dev = resolve_device(None)
            add("pytorch", True, f"{torch.__version__}, device={dev}")
        except Exception as exc:
            add("pytorch", False, str(exc))

        for mod, why in (("mdtraj", "trajectory i/o"),
                         ("matplotlib", "plots"),
                         ("scipy", "KL / FES estimation")):
            add(mod, _have(mod), why if _have(mod) else f"MISSING ({why})")
        for mod, why in (("optuna", "hyperparameter tuning"),
                         ("sklearn", "KMeans clustering fallback"),
                         ("hdbscan", "density-based pose clustering"),
                         ("plotly", "interactive latent plots"),
                         ("py3Dmol", "3-D structure viewer"),
                         ("pandas", "tuning / COLVAR tables"),
                         ("yaml", "project config")):
            add(f"{mod} (optional)", True if _have(mod) else None,
                why if _have(mod) else f"not installed -- {why} unavailable")

        from ..md.gromacs import check_environment
        for tool, ver in check_environment().items():
            found = "NOT" not in ver and "unknown" != ver
            add(tool, found if (require_gromacs or found) else None,
                ver if found else f"{ver} -- needed for the MD stage only")

        return PreflightReport(rows, project=self)

    # --------------------------------------------------------------- display
    def summary(self) -> str:
        lines = [f"Project {self.name!r}  (asmsa_v2 {self.asmsa_version})",
                 f"  root        {self.root}",
                 f"  conf        {self.conf}",
                 f"  traj        {self.traj}",
                 f"  components  {self.components or '(single molecule)'}",
                 f"  model       {self.model_name}  prior={self.prior}  "
                 f"latent_dim={self.latent_dim}"
                 + (f"  time_lag={self.time_lag}" if self.time_lag else ""),
                 f"  split       {self.split_strategy} {self.split_fractions}",
                 f"  md          {self.production_ns} ns @ {self.temperature} K"]
        lines.append("  stages:")
        for label, done in self.stage_status().items():
            lines.append(f"    [{'done' if done else '  --'}] {label}")
        return "\n".join(lines)

    def _repr_html_(self) -> str:
        rows = "".join(
            f"<tr><td style='padding:1px 8px;color:#57606a'>{k}</td>"
            f"<td style='padding:1px 8px'><code>{v}</code></td></tr>"
            for k, v in [
                ("root", self.root), ("conf", self.conf), ("traj", self.traj),
                ("components", self.components or "(single molecule)"),
                ("model", f"{self.model_name} / prior={self.prior} / "
                          f"latent_dim={self.latent_dim}"),
                ("split", f"{self.split_strategy} {self.split_fractions}"),
                ("md", f"{self.production_ns} ns @ {self.temperature} K"),
            ]
        )
        stages = "".join(
            f"<tr><td style='padding:1px 8px;color:{'#1a7f37' if d else '#8c959f'}'>"
            f"{'&#10003;' if d else '&#183;'}</td>"
            f"<td style='padding:1px 8px;color:{'#1a7f37' if d else '#8c959f'}'>"
            f"{k}</td></tr>"
            for k, d in self.stage_status().items()
        )
        return (
            f"<div style='font-size:92%'>"
            f"<table style='border-collapse:collapse'>"
            f"<caption style='text-align:left'><b>Project &lsquo;{self.name}&rsquo;</b>"
            f" &mdash; asmsa_v2 {self.asmsa_version}</caption>{rows}</table>"
            f"<table style='border-collapse:collapse;margin-top:6px'>"
            f"<caption style='text-align:left'><b>Pipeline stages</b></caption>"
            f"{stages}</table></div>"
        )

    def __repr__(self) -> str:
        return self.summary()

    # ----------------------------------------------------------------- prior
    def make_prior(self, latent_dim: int | None = None):
        """Instantiate the prior named by ``self.prior``."""
        from ..priors import GMMPrior, ImagePrior, IsotropicNormalPrior, gmm_on_circle

        d = int(latent_dim or self.latent_dim)
        spec = self.prior
        if spec in ("normal", "norm", "gaussian"):
            return IsotropicNormalPrior(d)
        if spec in ("mix", "gmm", "circle"):
            if d != 2:
                raise ValueError("the 'mix' prior is defined for latent_dim=2")
            return gmm_on_circle(K=10, radius=1.5, scale_std=0.15)
        if spec in ("uniform", "unif"):
            # A box prior; implemented as a wide GMM grid would distort it, so
            # build it explicitly from a uniform distribution.
            return _UniformPrior(d)
        p = self._resolve(spec)
        if p.exists():
            if d != 2:
                raise ValueError("an image prior is only defined for latent_dim=2")
            return ImagePrior(str(p))
        raise ValueError(
            f"unknown prior {spec!r}; use 'normal', 'uniform', 'mix', or a path "
            f"to a grayscale image"
        )


class _UniformPrior:
    """Uniform prior on ``[0, 1]^d`` (v1's ``tfp.distributions.Uniform``)."""

    def __init__(self, latent_dim: int):
        self.latent_dim = latent_dim
        self._device = "cpu"

    def to(self, device):
        self._device = device
        return self

    def sample(self, n: int):
        import torch
        return torch.rand(int(n), self.latent_dim, device=self._device)

    def log_prob(self, z):
        import torch
        inside = ((z >= 0) & (z <= 1)).all(dim=-1)
        return torch.where(
            inside, torch.zeros_like(inside, dtype=z.dtype),
            torch.full_like(inside, -1e9, dtype=z.dtype),
        )


@dataclass
class PreflightReport:
    """Result of :meth:`Project.check`."""

    rows: list[tuple[str, str, str]]
    project: Project | None = None

    @property
    def failures(self) -> list[tuple[str, str, str]]:
        return [r for r in self.rows if r[1] == "fail"]

    @property
    def ok(self) -> bool:
        return not self.failures

    def raise_if_failed(self) -> "PreflightReport":
        if not self.ok:
            detail = "\n".join(f"  - {label}: {d}" for label, _, d in self.failures)
            raise RuntimeError(f"preflight checks failed:\n{detail}")
        return self

    def summary(self) -> str:
        marks = {"ok": "ok  ", "warn": "warn", "fail": "FAIL"}
        lines = ["Preflight check"]
        for label, status, detail in self.rows:
            lines.append(f"  [{marks[status]}] {label:<30} {detail}")
        lines.append("  => " + ("all required checks passed"
                                if self.ok else
                                f"{len(self.failures)} FAILURE(S)"))
        return "\n".join(lines)

    def _repr_html_(self) -> str:
        colours = {"ok": "#1a7f37", "warn": "#9a6700", "fail": "#cf222e"}
        glyphs = {"ok": "&#10003;", "warn": "&#9888;", "fail": "&#10007;"}
        rows = "".join(
            f"<tr>"
            f"<td style='padding:1px 8px;color:{colours[s]}'>{glyphs[s]}</td>"
            f"<td style='padding:1px 8px'>{label}</td>"
            f"<td style='padding:1px 8px;color:#57606a;font-size:92%'>{d}</td></tr>"
            for label, s, d in self.rows
        )
        verdict = ("<span style='color:#1a7f37'><b>all required checks passed</b></span>"
                   if self.ok else
                   f"<span style='color:#cf222e'><b>{len(self.failures)} failure(s)"
                   f"</b></span>")
        return (
            "<table style='border-collapse:collapse;font-size:93%'>"
            f"<caption style='text-align:left;padding-bottom:3px'>"
            f"<b>Preflight check</b> &mdash; {verdict}</caption>"
            f"{rows}</table>"
        )

    def __repr__(self) -> str:
        return self.summary()


def _have(module: str) -> bool:
    if module in sys.modules:
        return True
    try:
        import importlib.util
        return importlib.util.find_spec(module) is not None
    except (ImportError, ValueError, ModuleNotFoundError):
        return False
